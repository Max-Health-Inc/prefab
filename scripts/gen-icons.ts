/**
 * Generate the renderer's icon glyphs from lucide-static, keyed by A2UI icon name.
 * The output is committed so the zero-dependency renderer needs no icon package at
 * runtime; `test/icons.test.ts` fails when an A2UI icon has no glyph.
 *
 * Run directly:  bun run scripts/gen-icons.ts
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { A2UI_ICONS } from '../src/a2ui/icons.js'

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const iconDir = join(repoRoot, 'node_modules', 'lucide-static', 'icons')
const targetFile = join(repoRoot, 'src', 'renderer', 'icons.generated.ts')

const LUCIDE_NAME: Record<string, string> = {
  accountCircle: 'circle-user-round', add: 'plus', arrowBack: 'arrow-left', arrowForward: 'arrow-right',
  attachFile: 'paperclip', calendarToday: 'calendar', call: 'phone', camera: 'camera', check: 'check',
  close: 'x', delete: 'trash-2', download: 'download', edit: 'pencil', event: 'calendar-days',
  error: 'circle-alert', fastForward: 'fast-forward', favorite: 'heart', favoriteOff: 'heart-off',
  folder: 'folder', help: 'circle-help', home: 'house', info: 'info', locationOn: 'map-pin',
  lock: 'lock', lockOpen: 'lock-open', mail: 'mail', menu: 'menu', moreVert: 'ellipsis-vertical',
  moreHoriz: 'ellipsis', notificationsOff: 'bell-off', notifications: 'bell', pause: 'pause',
  payment: 'credit-card', person: 'user', phone: 'smartphone', photo: 'image', play: 'play',
  print: 'printer', refresh: 'refresh-cw', rewind: 'rewind', search: 'search', send: 'send',
  settings: 'settings', share: 'share-2', shoppingCart: 'shopping-cart', skipNext: 'skip-forward',
  skipPrevious: 'skip-back', star: 'star', starHalf: 'star-half', starOff: 'star-off', stop: 'square',
  upload: 'upload', visibility: 'eye', visibilityOff: 'eye-off', volumeDown: 'volume-1',
  volumeMute: 'volume', volumeOff: 'volume-x', volumeUp: 'volume-2', warning: 'triangle-alert',
}

/** The child elements of one lucide SVG, whitespace collapsed. */
function glyph(lucide: string): string {
  const svg = readFileSync(join(iconDir, `${lucide}.svg`), 'utf8')
  const inner = /<svg[^>]*>([\s\S]*?)<\/svg>/.exec(svg)
  if (inner === null) throw new Error(`gen-icons: no <svg> in ${lucide}.svg`)
  return inner[1].replace(/\s*\n\s*/g, '').replace(/\s+\/>/g, '/>').trim()
}

export function genIcons(): void {
  const missing = A2UI_ICONS.filter(name => !(name in LUCIDE_NAME))
  if (missing.length > 0) throw new Error(`gen-icons: no lucide glyph mapped for ${missing.join(', ')}`)
  const entries = A2UI_ICONS.map(name => `  ${name}: '${glyph(LUCIDE_NAME[name])}',`).join('\n')
  writeFileSync(targetFile, `// Generated by scripts/gen-icons.ts from lucide-static (ISC License, https://lucide.dev). Do not edit.

/** SVG children of each A2UI icon, drawn on a 24×24 stroked canvas. */
export const ICON_GLYPHS: Readonly<Record<string, string>> = {
${entries}
}
`)
}

if (import.meta.main) genIcons()
